"""Gate *which members* the framework calls on addon-owned models.

``env_model_surface_check.py`` ratchets **which models** the core reaches by
string key -- 31 of them, exact-mode. It is deliberately one flat set of model
names, and its own docstring names the next step: "the argument for eventually
promoting their *interfaces* into core (Protocols in ``odoo/``, implementations
in ``base``)". This gate is the measurement that step needs, and the thing that
keeps a promoted interface honest afterwards.

**The gap it closes.** A model name is not a contract; the members called on it
are. The model gate is green for every one of the pairs below, because none of
them adds a *model*. Adding ``env["res.users"]._invent_a_hook()`` to ``orm/``
today passes ``env_model_surface_check``, ``layer_check``, ``env_surface_check``
and ``pool_surface_check``: four gates, all green, on a call to a method that
need not exist.

MEASURED (regenerated by --update-doc; do not hand-edit)
    pairs=69 models=22 with_protocol=1

Every figure quoted below comes from that block, and ``--check-doc`` fails when
they disagree -- wired into ``test_model_member_surface_check.py``. See
``doc_measured.py``.

**What is counted, and what is not.** Members ``BaseModel`` itself provides are
subtracted (:func:`base_model_members`): ``browse``, ``search``, ``sudo``,
``create``, ``with_context`` on ``env["res.users"]`` ask ``base`` for nothing it
did not inherit from the framework. Counting them put 46 further pairs in the
surface and buried the ones that are the real contract -- ``ir.model.data
._load_xmlid``, ``ir.attachment._filestore``, ``res.users._compute_session_token``
-- among them. What remains is the surface an addon must actually implement:
**69 pairs across 22 models**, of which **1 model has a declared interface.**

**And that one Protocol was already behind.** ``http/_protocols.py`` declares
``HttpExtension`` for ``ir.http``, the widest of the 22. Its only enforcement,
``addons/test_http/tests/test_ir_http_contract.py``, checks Protocol ->
implementation: everything *declared* must exist on ``ir.http``, with a
compatible signature. Nothing checked the other direction, so
``http/_serve.py``'s ``registry["ir.http"]._apply_max_upload_size()`` -- called
on every dispatched request -- was reached by core, absent from the Protocol,
and therefore unchecked in both existence and signature. This gate found it on
its first run and it was declared the same day. That is the second rule below:
**every member the core reaches on a model that has a Protocol must be declared
by it.**

Two rules, then:

* the ``(model, member)`` surface is ratcheted exact, like the model set: a new
  pair fails (coupling is acknowledged, not accreted), and a pair that
  disappears fails too (a genuine decoupling is committed rather than quietly
  reintroducible);
* a model listed in :data:`PROTOCOLS` must have **every** reached member
  declared by its Protocol class.

What it does not do is *require* a Protocol. Eight models are reached for three
or more members and have none (the report's ``no Protocol`` column); mandating
one here would be a gate voting on work it cannot do. It makes the width visible
instead, and holds the line wherever the work has been done.

Usage::

  python tooling/architecture/model_member_surface_check.py            # report
  python tooling/architecture/model_member_surface_check.py --check    # CI
  python tooling/architecture/model_member_surface_check.py --json
  python tooling/architecture/model_member_surface_check.py --print-baseline
  python tooling/architecture/model_member_surface_check.py --update-doc
"""

