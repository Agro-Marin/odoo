from __future__ import annotations

import re
from pathlib import Path

MARKER = "MEASURED (regenerated by --update-doc; do not hand-edit)"

_BLOCK = re.compile(
    r"^(?P<indent>[ \t]*)"
    + re.escape(MARKER)
    + r"[ \t]*\n"
    + r"(?P<vindent>[ \t]+)(?P<values>\S.*)$",
    re.MULTILINE,
)

_PAIR = re.compile(r"([A-Za-z_][\w]*)=(-?\d+)")


class DocMeasuredError(Exception):
    pass


def render(metrics: dict[str, int]) -> str:
    return " ".join(f"{k}={v}" for k, v in metrics.items())


def extract(text: str) -> dict[str, int]:

    match = _BLOCK.search(text)
    if not match:
        raise DocMeasuredError(f"no MEASURED block found (marker: {MARKER!r})")
    pairs = _PAIR.findall(match.group("values"))
    if not pairs:
        raise DocMeasuredError(
            f"MEASURED block holds no key=value pair: {match.group('values')!r}"
        )
    return {k: int(v) for k, v in pairs}


def check(path: Path, metrics: dict[str, int]) -> list[str]:

    claimed = extract(path.read_text(encoding="utf-8"))
    problems = []
    for key in sorted(set(claimed) | set(metrics)):
        if key not in claimed:
            problems.append(
                f"{key}: missing from the docstring, measured {metrics[key]}"
            )
        elif key not in metrics:
            problems.append(
                f"{key}: in the docstring ({claimed[key]}), no longer measured"
            )
        elif claimed[key] != metrics[key]:
            problems.append(
                f"{key}: docstring says {claimed[key]}, measured {metrics[key]}"
            )
    return problems


def update(path: Path, metrics: dict[str, int]) -> bool:
    text = path.read_text(encoding="utf-8")
    match = _BLOCK.search(text)
    if not match:
        raise DocMeasuredError(f"no MEASURED block found (marker: {MARKER!r})")
    line = f"{match.group('vindent')}{render(metrics)}"
    if line == match.group("vindent") + match.group("values"):
        return False
    start, end = match.span("vindent"), match.span("values")
    new = text[: start[0]] + line + text[end[1] :]
    path.write_text(new, encoding="utf-8")
    return True


def main_flags(parser) -> None:
    parser.add_argument(
        "--check-doc",
        action="store_true",
        help="fail if the module docstring's MEASURED block is stale",
    )
    parser.add_argument(
        "--update-doc",
        action="store_true",
        help="rewrite the module docstring's MEASURED block",
    )
