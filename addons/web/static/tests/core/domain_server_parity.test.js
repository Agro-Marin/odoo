function pinCorpusDatabaseShape() {
    patchWithCleanup(session, { has_unaccent: true });
}

/**
 * @param {string} field
 * @param {string} operator
 * @param {any} value
 */
function caseKey(field, operator, value) {
    return `${field}|${operator}|${JSON.stringify(value)}`;
}

/**
 * @param {string} field
 * @param {string} operator
 * @param {any} value
 * @returns {string | null}
 */
function clientVerdict(field, operator, value) {
    let domain;
    try {
        domain = new Domain([[field, operator, value]]);
    } catch {
        return null;
    }
    let bits = "";
    for (const record of RECORDS) {
        try {
            bits += domain.contains(record) ? "1" : "0";
        } catch {
            return null;
        }
    }
    return bits;
}

test("Domain.contains agrees with the server's filtered_domain()", () => {
    pinCorpusDatabaseShape();
    const disagreements = [];
    for (const [field, operator, value, expected] of CASES) {
        if (KNOWN_DIVERGENCES.has(caseKey(field, operator, value))) {
            continue;
        }
        const got = clientVerdict(field, operator, value);
        if (got !== expected) {
            disagreements.push(
                `(${field}, ${operator}, ${JSON.stringify(value)}): ` +
                    `server=${expected} client=${got}`,
            );
        }
    }
    expect(disagreements).toEqual([]);
});

test("the type-blindness gap has not grown or silently closed", () => {
    pinCorpusDatabaseShape();
    const nowDivergent = new Set();
    for (const [field, operator, value, expected] of CASES) {
        if (clientVerdict(field, operator, value) !== expected) {
            nowDivergent.add(caseKey(field, operator, value));
        }
    }
    const appeared = [...nowDivergent].filter((k) => !KNOWN_DIVERGENCES.has(k));
    const fixed = [...KNOWN_DIVERGENCES].filter((k) => !nowDivergent.has(k));
    expect(appeared).toEqual([]);
    expect(fixed).toEqual([]);
});

describe("operand-shape rewrites the server applies before matching", () => {
    const RECS = [
        { id: 1, type: "contact", n: 0, ref: "R1" },
        { id: 2, type: "invoice", n: 5, ref: "R2" },
        { id: 3, type: "other", n: 0, ref: false },
    ];
    const ids = (/** @type {any} */ d) => new Domain(d).filter(RECS).map((r) => r.id);

    test("`=` / `!=` against a collection is `in` / `not in`", () => {
        expect(ids([["type", "=", ["contact", "invoice"]]])).toEqual([1, 2]);
        expect(ids([["type", "!=", ["contact", "invoice"]]])).toEqual([3]);
        expect(ids([["type", "==", ["other"]]])).toEqual([3]);
        expect(ids([["type", "<>", ["other"]]])).toEqual([1, 2]);
        expect(
            new Domain([["tag_ids", "=", [1, 2]]]).filter([
                { id: 1, tag_ids: [1] },
                { id: 2, tag_ids: [1, 2] },
                { id: 3, tag_ids: [9] },
            ]),
        ).toHaveLength(2);
    });

    test("an empty collection compares with False", () => {
        expect(ids([["ref", "=", []]])).toEqual([3]);
        expect(ids([["ref", "!=", []]])).toEqual([1, 2]);
    });

    test("`in` / `not in` against a falsy value is a constant", () => {
        expect(ids([["n", "in", 0]])).toEqual([]);
        expect(ids([["n", "not in", 0]])).toEqual([1, 2, 3]);
        expect(ids([["ref", "in", ""]])).toEqual([]);
        expect(ids([["ref", "not in", false]])).toEqual([1, 2, 3]);
        expect(ids([["n", "in", []]])).toEqual([]);
        expect(ids([["n", "not in", []]])).toEqual([1, 2, 3]);
        expect(ids([["type", "in", "contact"]])).toEqual([1]);
    });

    test("the `like` family stringifies a non-string pattern as Python does", () => {
        expect(ids([["ref", "like", ["R1"]]])).toEqual([]);
        expect(ids([["ref", "like", "R1"]])).toEqual([1]);
        expect(
            new Domain([["ref", "like", true]]).filter([{ id: 1, ref: "isTrue" }]),
        ).toHaveLength(1);
        expect(
            new Domain([["ref", "like", true]]).filter([{ id: 1, ref: "istrue" }]),
        ).toHaveLength(0);
    });

    test("the anchored `like` operators reject a non-string pattern, as the server does", () => {
        for (const operator of ["=like", "=ilike", "not =like", "not =ilike"]) {
            expect(() => ids([["ref", operator, ["R1"]]])).toThrow(/must be a string/, {
                message: operator,
            });
        }
        expect(() => ids([["ref", "like", ["R1"]]])).not.toThrow();
    });
});
