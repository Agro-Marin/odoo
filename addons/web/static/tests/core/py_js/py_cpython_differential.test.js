function canon(/** @type {any} */ v) {
    if (v === true) {
        return "True";
    }
    if (v === false) {
        return "False";
    }
    if (v === null) {
        return "None";
    }
    if (typeof v === "number") {
        if (!Number.isFinite(v)) {
            return "nonfinite";
        }
        return Number.isInteger(v) ? String(v) : String(v);
    }
    if (typeof v === "string") {
        return "s:" + v;
    }
    if (Array.isArray(v)) {
        return "[" + v.map(canon).join(",") + "]";
    }
    if (v instanceof Set) {
        return "{" + [...v].map(canon).sort().join(",") + "}";
    }
    if (typeof v === "object") {
        return (
            "{" +
            Object.keys(v)
                .sort()
                .map((k) => k + ":" + canon(v[k]))
                .join(",") +
            "}"
        );
    }
    return "?" + typeof v;
}

