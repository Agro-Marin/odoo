test("py_js matches CPython across the generated corpus", () => {
    /** @type {string[]} */
    const divergences = [];
    for (const [expr, kind, expected] of CORPUS) {
        let got;
        let threw = false;
        try {
            got = canon(evaluateExpr(expr));
        } catch (e) {
            threw = true;
            got = e.message;
        }
        if (kind === "err") {
            if (!threw) {
                divergences.push(`${expr} -> ${got}, CPython raises ${expected}`);
            } else if (!got.includes(expected)) {
                divergences.push(`${expr} -> ${got}, CPython raises ${expected}`);
            }
        } else if (threw) {
            divergences.push(`${expr} -> threw, CPython gives ${expected}`);
        } else if (got !== expected) {
            divergences.push(`${expr} -> ${got}, CPython gives ${expected}`);
        }
    }
    expect(divergences).toEqual([]);
});
