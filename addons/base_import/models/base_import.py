class Base_ImportImport(models.TransientModel):
    """
    This model is used to prepare the loading of data coming from a user file.

    Here is the process that is followed:

    #. The user selects a file to import.
    #. File parsing and mapping suggestion (see "parse_preview" method)

       #. Extract the current model's importable fields tree (see :meth:`get_fields_tree`).
       #. Read the file (see :meth:`_read_file`) and extract header names and file
          length (used for batch import).
       #. Extract headers types from the data preview (10 first line of the file)
          (see :meth:`_extract_headers_types`).
       #. Try to find for each header a field to map with (see :meth:`_get_mapping_suggestions`)

          - First check the previously saved mappings between the header name
            and one of the model's fields.
          - If no mapping found, try an exact match comparison using fields
            technical names, labels and user language translated labels.
          - If nothing found, try a fuzzy match using word distance between
            header name and fields tachnical names, labels and user language
            translated labels. Keep only the closest match.

       #. Prepare examples for each columns using the first non null value from each column.
       #. Send the info back to the UI where the user can modify the suggested mapping.
    #. Execute the import: There are two import mode with uses the same process. (see :meth:`execute_import`)

       #. Test import: Try to import but rollback the transaction. This allows
          the check errors during the import process and allow the user to
          choose import options for the different encountered errors.
       #. Real import: Try to import the file using the configured mapping and
          the eventual "error mapping options". If import encounters blocking
          errors, the transaction is rollbacked and the user is allowed to
          choose import options for the different errors.

          - Get file data and fields to import into (see :meth:`_convert_import_data`).
          - Parse date, float and binary data (see :meth:`_parse_import_data`).
          - Handle multiple mapping -> concatenate char/text/many2many columns
            mapped on the same field (see :meth:`_handle_multi_mapping`).
          - Handle fallback values for boolean and selection fields, in case
            input data does not match any allowed values (see :meth:`_handle_fallback_values`).
          - Load data (see ir.model "load" method).
          - Rollback transaction if test mode or if encountered error.
          - Save mapping if any import is successful to ease later mapping suggestions.
          - Return import result to the UI (success or errors if any).
    """
    _name = 'base_import.import'
    _description = 'Base Import'

    # allow imports to survive for 12h in case user is slow
    _transient_max_hours = 12.0
    # we consider that if the difference is more than 0.2, then the two compared strings are "too different" to propose
    # any match between them. (see '_get_mapping_suggestion' for more details)
    FUZZY_MATCH_DISTANCE = 0.2

    res_model = fields.Char('Model')
    file = fields.Binary('File', help="File to check and/or import, raw binary (not base64)", attachment=False)
    file_name = fields.Char('File Name')
    file_type = fields.Char('File Type')

    @api.model
    def get_fields_tree(self, model, depth=FIELDS_RECURSION_LIMIT):
        """ Recursively get fields for the provided model (through
        fields_get) and filter them according to importability

        The output format is a list of :class:`Field`:

        .. class:: Field

            .. attribute:: id: str

                A non-unique identifier for the field, used to compute
                the span of the ``required`` attribute: if multiple
                ``required`` fields have the same id, only one of them
                is necessary.

            .. attribute:: name: str

                The field's logical (Odoo) name within the scope of
                its parent.

            .. attribute:: string: str

                The field's human-readable name (``@string``)

            .. attribute:: required: bool

                Whether the field is marked as required in the
                model. Clients must provide non-empty import values
                for all required fields or the import will error out.

            .. attribute:: fields: list[Field]

                The current field's subfields. The database and
                external identifiers for m2o and m2m fields; a
                filtered and transformed fields_get for o2m fields (to
                a variable depth defined by ``depth``).

                Fields with no sub-fields will have an empty list of
                sub-fields.

            .. attribute:: model_name: str

                Used in the Odoo Field Tooltip on the import view
                and to get the model of the field of the related field(s).
                Name of the current field's model.

            .. attribute:: comodel_name: str

                Used in the Odoo Field Tooltip on the import view
                and to get the model of the field of the related field(s).
                Name of the current field's comodel, i.e. if the field is a relation field.

        Structure example for 'crm.team' model for returned importable_fields::

            [
                {'name': 'message_ids', 'string': 'Messages', 'model_name': 'crm.team', 'comodel_name': 'mail.message', 'fields': [
                    {'name': 'moderation_status', 'string': 'Moderation Status', 'model_name': 'mail.message', 'fields': []},
                    {'name': 'body', 'string': 'Contents', 'model_name': 'mail.message', 'fields' : []}
                ]},
                {{'name': 'name', 'string': 'Sales Team', 'model_name': 'crm.team', 'fields' : []}
            ]

        :param str model: name of the model to get fields form
        :param int depth: depth of recursion into o2m fields, clamped to
            :data:`FIELDS_RECURSION_LIMIT`
        """
        # This method is a public (RPC-callable) entry point and `depth` is
        # caller-supplied, so it is an unauthenticated-shaped amplification
        # knob: each extra level multiplies the result by ~2-4x (measured over
        # JSON-RPC on res.partner: depth 3 -> 0.5 MiB, depth 7 -> 11 MiB,
        # depth 9 -> 47 MiB), and nothing refused the call. Clamp rather than
        # raise: enterprise overrides pass `depth` straight through, and the
        # only legitimate callers use the default.
        depth = min(depth, FIELDS_RECURSION_LIMIT)
        # `model` is caller-supplied over RPC and nothing checked it. Defence
        # in depth rather than a closed hole: measured, the tree is *narrower*
        # than the `fields_get` it wraps (14 fields vs 21 on ir.mail_server for
        # a plain internal user, since readonly and magic columns are dropped),
        # so it discloses nothing that model's own `fields_get` does not
        # already hand out. What it adds is reach -- one call walks ~49
        # comodels, three levels deep. Checked on the entry model only: the
        # recursion below legitimately descends into comodels a user may not
        # read directly but must still be able to map onto.
        self.env[model].check_access('read')
        return self._get_fields_tree(model, depth)

    def _get_fields_tree(self, model, depth):
        """ Recursive body of :meth:`get_fields_tree`, without its access
        check -- see the note there on why the check is not repeated per level.
        """
        Model = self.env[model]
        importable_fields = [{
            'id': 'id',
            'name': 'id',
            'string': _("External ID"),
            'required': False,
            'fields': [],
            'type': 'id',
            'model_name': model,
        }]
        if not depth:
            return importable_fields

        model_fields = Model.fields_get(attributes=[
            'string', 'required', 'type', 'readonly', 'relation', 'selection',
            'definition_record', 'definition_record_field',
        ])
        blacklist = models.MAGIC_COLUMNS

        for name, field in dict(model_fields).items():
            # `not in 'properties'` was a substring test against the *string*
            # "properties", not a type comparison: it happened to behave for
            # today's field types only because none of them is a substring of
            # "properties".
            if field['type'] != 'properties':
                continue
            definition_record = field['definition_record']
            definition_record_field = field['definition_record_field']

            target_model = Model.env[Model._fields[definition_record].comodel_name]

            # ignore if you cannot access to the target model or the field definition
            if not target_model.has_access('read'):
                continue
            if not target_model._has_field_access(target_model._fields[definition_record_field], 'read'):
                continue

            # Do not take into account the definition of archived parents,
            # we do not import archived records most of the time.
            definition_records = target_model.search_fetch(
                [(definition_record_field, '!=', False)],
                [definition_record_field, 'display_name'],
                order='id',  # Avoid complex order
            )

            for record in definition_records:
                for definition in record[definition_record_field]:
                    definition_type = definition['type']
                    if (
                        definition_type == 'separator' or
                        (
                            definition_type in ('many2one', 'many2many')
                            and definition.get('comodel') not in Model.env
                        )
                    ):
                        continue
                    id_field = f"{name}.{definition['name']}"
                    model_fields[id_field] = {
                        'type': definition_type,
                        'string': _(
                            "%(property_string)s (%(parent_name)s)",
                            property_string=definition['string'], parent_name=record.display_name,
                        ),
                    }
                    if definition_type in ('many2one', 'many2many'):
                        model_fields[id_field]['relation'] = definition['comodel']
                    elif definition_type == 'selection':
                        model_fields[id_field]['selection'] = definition.get('selection') or []

        for name, field in model_fields.items():
            if name in blacklist:
                continue
            if field.get('readonly'):
                continue
            field_value = {
                'id': name,
                'name': name,
                'string': field['string'],
                # Y U NO ALWAYS HAS REQUIRED
                'required': bool(field.get('required')),
                'fields': [],
                'type': field['type'],
                'model_name': model,
            }

            if field['type'] == 'selection':
                # A Properties sub-column is not a field of `model`, so the
                # client cannot recover its selection with a second fields_get.
                field_value['selection'] = field.get('selection') or []

            if field['type'] in ('many2many', 'many2one'):
                field_value['fields'] = [
                    dict(field_value, model_name=field['relation'], name='id', string=_("External ID"), type='id'),
                    dict(field_value, model_name=field['relation'], name='.id', string=_("Database ID"), type='id'),
                ]
                field_value['comodel_name'] = field['relation']
            elif field['type'] == 'one2many':
                field_value['fields'] = self._get_fields_tree(field['relation'], depth=depth-1)
                if self.env.user.has_group('base.group_no_one'):
                    field_value['fields'].append(
                        dict(field_value, model_name=field['relation'], fields=[], name='.id', string=_("Database ID"), type='id')
                    )
                field_value['comodel_name'] = field['relation']

            importable_fields.append(field_value)

        return importable_fields

    def _filter_fields_by_types(self, model_fields_tree, header_types):
        """ Narrow ``model_fields_tree`` to the fields worth fuzzy-matching a
        column whose values look like ``header_types``.

        **Scalar** fields are kept only if their type is in ``header_types``.
        **Relational** fields (anything carrying subfields) are kept
        unconditionally, and filtered recursively inside. That is deliberate,
        not an oversight: a column of integers can perfectly well be a
        many2one addressed by database id, so its type says nothing about
        whether the header names a relation. The consequence is worth knowing
        before "tightening" this -- for ``header_types=['integer']`` on
        res.partner it keeps 24 of 56 fields, 22 of them relational -- because
        moving the type test out of the ``elif`` would silently change every
        suggestion the module makes.

        :param list[dict] model_fields_tree: Contains recursively all the importable fields of
            the target model. Generated in :meth:`get_fields_tree`.
        :param list header_types: Contains the extracted fields types of the current header.
            Generated in :meth:`_extract_header_types`.
        """
        # 'all' is the sentinel `_extract_header_types` returns for a column
        # whose preview rows are all empty: nothing is known about it, so every
        # field is a candidate. Without this case the filter kept only fields
        # that have subfields -- i.e. only relational ones -- so an empty column
        # silently lost every fuzzy suggestion it would otherwise have got
        # (header "Functon" matched `function` when the column had data, and
        # matched nothing at all when it did not).
        if 'all' in header_types:
            return model_fields_tree

        most_likely_fields_tree = []
        for field in model_fields_tree:
            subfields = field.get('fields')
            if subfields:
                filtered_field = dict(field)  # Avoid modifying fields.
                filtered_field['fields'] = self._filter_fields_by_types(subfields, header_types)
                most_likely_fields_tree.append(filtered_field)
            elif field.get('type') in header_types:
                most_likely_fields_tree.append(field)
        return most_likely_fields_tree

    def _read_file(self, options):
        """ Dispatch to the reader for this file's format, deduced from its
        content, its declared mimetype, or its extension (in that order).

        :param dict options: reading options (quoting, separator, ...)
        :returns: the file's non-empty rows
        :rtype: list[list]
        """
        self.ensure_one()

        # guess mimetype from file content
        mimetype = guess_mimetype(self.file or b'')
        extensions_to_try = [
            (MIMETYPE_TO_READER.get(mimetype), f"guessed using mimetype {mimetype!r}"),
            (MIMETYPE_TO_READER.get(self.file_type), f"decided from user-provided mimetype {self.file_type!r}"),
        ]
        # fallback on file extensions as mime types can be unreliable (e.g.
        # software setting incorrect mime types, or non-installed software
        # leading to browser not sending mime types)
        if self.file_name:
            ext = Path(self.file_name).suffix
            extensions_to_try.append((ext.removeprefix('.').lower(), f"decided from file extension {ext!r}"))

        e = None
        requires = None
        requires_extension = None
        tried_extensions = set()
        for file_extension, guess_message in extensions_to_try:
            if not file_extension or file_extension in tried_extensions:
                continue
            tried_extensions.add(file_extension)
            # Allow-list lookup, never `getattr(self, '_read_' + <user input>)`:
            # see EXTENSION_TO_READER for what that used to make reachable.
            handler_name = EXTENSION_TO_READER.get(file_extension)
            if not handler_name:
                continue
            try:
                return getattr(self, handler_name)(options)
            except ImportError as exc:
                # exc.name_from attribute is present as of python 3.12
                requires = str(getattr(exc, 'name_from', None) or exc.name)
                requires_extension = file_extension
            except (ImportValidationError, ValueError):
                raise
            except Exception as exc:
                e = read_file_failed(exc, f"Unable to read file {self.file_name or '<unknown>'!r} as {file_extension!r} ({guess_message}).")

        if e is not None:
            raise e

        if requires:
            # `requires_extension`, not the loop variable: the latter holds
            # whichever candidate was tried *last*, which is not necessarily the
            # one whose reader was missing its optional dependency.
            raise UserError(_(
                'Unable to load "%(extension)s" file: requires Python module "%(modname)s"',
                extension=requires_extension, modname=requires,
            ))
        raise UserError(_(
            'Unsupported file format "%(file_type)s", import only supports %(supported)s',
            file_type=self.file_type or (self.file_name or ''),
            supported=', '.join(sorted(EXTENSION_TO_READER)),
        ))

    def _read_xls(self, options):
        # Lazy import, mirroring _read_xlsx's `import openpyxl` and _read_ods's
        # `from . import odf_ods_reader`: `xlrd` is an optional format library
        # (not in requirements.txt, unlike chardet/Pillow/psycopg above), and a
        # module-level `import xlrd` used to make the WHOLE base_import module
        # fail to load if it were ever absent, instead of only ".xls" support
        # becoming unavailable via _read_file's existing `except ImportError`
        # handling (t24068 F20).
        import xlrd

        book = xlrd.open_workbook(file_contents=self.file or b'')
        sheets = options['sheets'] = book.sheet_names()
        sheet_name = options['sheet'] = options.get('sheet') or sheets[0]
        sheet = book.sheet_by_name(sheet_name)
        rows = []
        for rowx, row in enumerate(map(sheet.row, range(sheet.nrows)), 1):
            values = []
            for colx, cell in enumerate(row, 1):
                if cell.ctype is xlrd.XL_CELL_NUMBER:
                    if cell.value % 1 == 0:
                        values.append(str(int(cell.value)))
                    else:
                        values.append(str(cell.value))
                elif cell.ctype is xlrd.XL_CELL_DATE:
                    dt = datetime.datetime(
                        *xlrd.xldate.xldate_as_tuple(cell.value, book.datemode)
                    )
                    values.append(dt if cell.value % 1 else dt.date())
                elif cell.ctype is xlrd.XL_CELL_BOOLEAN:
                    values.append('True' if cell.value else 'False')
                elif cell.ctype is xlrd.XL_CELL_ERROR:
                    raise ValueError(_(
                        "Invalid cell value at row %(row)s, column %(col)s: %(cell_value)s",
                        row=rowx,
                        col=colx,
                        cell_value=xlrd.error_text_from_code.get(
                            cell.value, _("unknown error code %s", cell.value)
                        ),
                    ))
                else:
                    values.append(cell.value)
            if any(x and (not isinstance(x, str) or x.strip()) for x in values):
                rows.append(values)
        return rows

    def _read_xlsx(self, options):
        import openpyxl
        import openpyxl.cell.cell as types
        import openpyxl.styles.numbers as styles
        book = openpyxl.load_workbook(io.BytesIO(self.file or b''), data_only=True, read_only=True)
        try:
            sheets = options['sheets'] = book.sheetnames
            sheet_name = options['sheet'] = options.get('sheet') or sheets[0]
            sheet = book[sheet_name]
            rows = []
            for rowx, row in enumerate(sheet.rows, 1):
                values = []
                for colx, cell in enumerate(row, 1):
                    if cell.data_type == types.TYPE_ERROR:
                        raise ValueError(
                            _("Invalid cell value at row %(row)s, column %(col)s: %(cell_value)s", row=rowx, col=colx, cell_value=cell.value)
                        )

                    if cell.value is None:
                        values.append('')
                    elif isinstance(cell.value, float):
                        if cell.value % 1 == 0:
                            values.append(str(int(cell.value)))
                        else:
                            values.append(str(cell.value))
                    elif cell.is_date:
                        d_fmt = styles.is_datetime(cell.number_format)
                        if d_fmt == "datetime":
                            values.append(cell.value)
                        elif d_fmt == "date":
                            values.append(cell.value.date())
                        else:
                            raise ValueError(
                            _("Invalid cell format at row %(row)s, column %(col)s: %(cell_value)s, with format: %(cell_format)s, as (%(format_type)s) formats are not supported.", row=rowx, col=colx, cell_value=cell.value, cell_format=cell.number_format, format_type=d_fmt)
                            )
                    else:
                        values.append(str(cell.value))

                if any(x and (not isinstance(x, str) or x.strip()) for x in values):
                    rows.append(values)
            return rows
        finally:
            book.close()

    def _read_ods(self, options):
        from . import odf_ods_reader
        doc = odf_ods_reader.ODSReader(file=io.BytesIO(self.file or b''))
        sheets = options['sheets'] = list(doc.sheets)
        if not sheets:
            raise ImportValidationError(_("Import file has no content or is corrupt"))
        # A stale/hand-crafted `sheet` option must not IndexError or KeyError
        # its way out of the reader; fall back to the first sheet.
        sheet = options.get('sheet')
        if sheet not in doc.sheets:
            sheet = sheets[0]
        options['sheet'] = sheet

        # The reader already drops blank rows, including the repeated blank
        # tail every producer writes.
        return doc.get_sheet(sheet)

    def _read_csv(self, options):
        """ Returns a CSV-parsed list of all non-empty lines in the file.

        :raises csv.Error: if an error is detected during CSV parsing
        """
        # Validated before any use of `quoting` below. It used to be checked
        # only *after* the separator-sniffing loop had already handed it to
        # csv.reader, so whenever the separator was auto-detected (the default)
        # the user got csv's raw `TypeError: "quotechar" must be a unicode
        # character` instead of this actionable message.
        quoting = options.setdefault('quoting', '"')
        if not isinstance(quoting, str) or len(quoting) != 1:
            raise ImportValidationError(_("Error while importing records: Text Delimiter should be a single character."))

        csv_data = self.file or b''
        if not csv_data:
            return []

        encoding = options.get('encoding')
        encoding_guessed = False
        if not encoding:
            encoding_guessed = True
            detected_encoding = _detect_encoding(csv_data)
            if not detected_encoding:
                # chardet returns encoding=None for ambiguous/undetectable byte
                # content; used to crash here with AttributeError (t24068 F19).
                raise ImportValidationError(_("Could not detect the file's encoding, please select it manually."))
            encoding = options['encoding'] = detected_encoding.lower()
            # some versions of chardet (e.g. 2.3.0 but not 3.x) will return
            # utf-(16|32)(le|be), which for python means "ignore / don't strip
            # BOM". We don't want that, so rectify the encoding to non-marked
            # IFF the guessed encoding is LE/BE and csv_data starts with a BOM
            bom = BOM_MAP.get(encoding)
            if bom and csv_data.startswith(bom):
                encoding = options['encoding'] = encoding[:-2]

        try:
            csv_text = csv_data.decode(encoding)
        except UnicodeDecodeError as exc:
            if encoding_guessed:
                msg = _("There was an issue decoding the file using encoding “%s”.\nThis encoding was automatically detected.", encoding)
            else:
                msg = _("There was an issue decoding the file using encoding “%s”.\nThis encoding was manually selected.", encoding)
            raise ImportValidationError(msg) from exc

        separator = options.get('separator')
        if not separator:
            # default for unspecified separator so user gets a message about
            # having to specify it
            separator = ','
            for candidate in (',', ';', '\t', ' ', '|', unicodedata.lookup('unit separator')):
                # Check whether the first rows all split to the same, >1 width;
                # if so assume this is the right delimiter. Bounded to
                # SEPARATOR_SNIFF_ROWS: a delimiter that happens to be
                # consistent (e.g. ',' on a file with one comma per line) used
                # to drag the whole decoded file through csv.reader once per
                # candidate before being accepted or rejected.
                it = csv.reader(io.StringIO(csv_text), quotechar=quoting, delimiter=candidate)
                w = None
                for row in itertools.islice(it, SEPARATOR_SNIFF_ROWS):
                    width = len(row)
                    if w is None:
                        w = width
                    if width == 1 or width != w:
                        break  # next candidate
                else:  # nobreak
                    separator = options['separator'] = candidate
                    break

        csv_iterator = csv.reader(
            io.StringIO(csv_text),
            quotechar=quoting,
            delimiter=separator)

        return [
            row for row in csv_iterator
            if any(x for x in row if x.strip())
        ]

    @api.model
    def _extract_header_types(self, preview_values, options):
        """ Returns the potential field types, based on the preview values, using heuristics.

        This methods is only used for suggested mapping at 2 levels:

        1. for fuzzy mapping at file load -> Execute the fuzzy mapping only
           on "most likely field types"
        2. For "Suggested fields" section in the fields mapping dropdown list at UI side.

        The following heuristic is used: If all preview values

        - Start with ``__export__``: return id + relational field types
        - Can be cast into integer: return integer, float and monetary (and boolean if values are only 0 and 1)
        - Can be cast into Boolean: return boolean
        - Can be cast into float: return float, monetary
        - Can be cast into date/datetime: return date / datetime
        - Cannot be cast into any of the previous types: return only text based fields

        :param preview_values: list of value for the column to determine
                               see :meth:`parse_preview` for more details.
        :param options: parsing options
        """
        # Nothing to go on at all -- a header-only file, so every field is a
        # candidate. This is the same answer as the all-blank case below, but
        # it has to be reached first: `values` is then the *empty* set, which
        # is not `{''}`, and every `all(...)` test below is vacuously true over
        # it. Control therefore fell into the `__export__` branch and typed
        # every column of every header-only file as id/relational, which
        # `_filter_fields_by_types` then narrowed to relational fields only --
        # so a template uploaded before its data got no mapping suggestions at
        # all, while the same file with one data row mapped correctly.
        if not preview_values:
            return ['all']

        if all(isinstance(v, str) for v in preview_values):
            preview_values = [v.strip() for v in preview_values]
            values = set(preview_values)
            # If all values are empty in preview than can be any field
            if values == {''}:
                return ['all']

            # If all values starts with __export__ this is probably an id
            if all(v.startswith('__export__') for v in values):
                return ['id', 'many2many', 'many2one', 'one2many']

            # If all values can be cast to int type is either integer, float or monetary
            # Exception: if we only have 1 and 0, it can also be a boolean
            # `str.isdigit` was both too narrow and too wide here: it rejects
            # "-1" (a column of negative integers was typed as float/monetary,
            # so integer fields never showed up as suggestions) and it accepts
            # non-ASCII digits such as "٣" or "²", for which int() then fails.
            if all(_is_integer_literal(v) for v in values if v):
                field_type = ['integer', 'float', 'monetary']
                if {'0', '1', ''}.issuperset(values):
                    field_type.append('boolean')
                return field_type

            # If all values are either True or False, type is boolean
            if all(val.lower() in ('true', 'false', 't', 'f', '') for val in preview_values):
                return ['boolean']

            # If all values can be cast to float, type is either float or monetary
            try:
                thousand_separator = decimal_separator = False
                currency_symbols = None
                for val in preview_values:
                    val = val.strip()
                    if not val:
                        continue
                    # value might have the currency symbol left or right from the value
                    # (looked up once per column, lazily, instead of once per value)
                    if currency_symbols is None:
                        currency_symbols = self._currency_symbols()
                    val = self._remove_currency_symbol(val, currency_symbols)
                    if val:
                        if options.get('float_thousand_separator') and options.get('float_decimal_separator'):
                            if options['float_decimal_separator'] == '.' and val.count('.') > 1:
                                # not a float: leave the try block
                                raise ValueError(val)
                            val = val.replace(options['float_thousand_separator'], '').replace(options['float_decimal_separator'], '.')
                        # We are now sure that this is a float, but we still need to find the
                        # thousand and decimal separator
                        elif val.count('.') > 1:
                            options['float_thousand_separator'] = '.'
                            options['float_decimal_separator'] = ','
                        elif val.count(',') > 1:
                            options['float_thousand_separator'] = ','
                            options['float_decimal_separator'] = '.'
                        elif val.find('.') > val.find(','):
                            thousand_separator = ','
                            decimal_separator = '.'
                        elif val.find(',') > val.find('.'):
                            thousand_separator = '.'
                            decimal_separator = ','
                    else:
                        # not a float: leave the try block
                        raise ValueError(val)
                if thousand_separator and not options.get('float_decimal_separator'):
                    options['float_thousand_separator'] = thousand_separator
                    options['float_decimal_separator'] = decimal_separator
                return ['float', 'monetary']  # Allow float to be mapped on a text field.
            except ValueError:
                pass

        results = self._try_match_date_time(preview_values, options)
        if results:
            return results

        # If not boolean, date/datetime, float or integer, only suggest text based fields.
        return ['text', 'char', 'binary', 'selection', 'html', 'tags']

    def _try_match_date_time(self, preview_values, options):
        # Or a date/datetime if it matches the pattern
        date_patterns = [options['date_format']] if options.get(
            'date_format') else []
        user_date_format = self.env['res.lang']._get_data(code=self.env.user.lang).date_format
        if user_date_format:
            try:
                to_re(user_date_format)
                date_patterns.append(user_date_format)
            except KeyError:
                pass
        date_patterns.extend(DATE_PATTERNS)
        match = check_patterns(date_patterns, preview_values)
        if match:
            options['date_format'] = match
            return ['date', 'datetime']

        datetime_patterns = [options['datetime_format']] if options.get(
            'datetime_format') else []
        datetime_patterns.extend(
            "%s %s" % (d, t)
            for d in date_patterns
            for t in TIME_PATTERNS
        )
        match = check_patterns(datetime_patterns, preview_values)
        if match:
            options['datetime_format'] = match
            return ['datetime']

        return []

    @api.model
    def _extract_headers_types(self, headers, preview, options):
        """
        For each column, this method will extract the potential data types based on the preview values

        :param list headers: list of headers names. Used as part of key for
                             returned headers_types to ease understanding of its usage
        :param list preview: list of the first file records (see "parse_preview" for more detail) e.g.::

            [ ["lead_name1", "1", "partner_id1"], ["lead_name2", "2", "partner_id2"], ... ]

        :param options: parsing options
        :returns: dict headers_types:

            contains all the extracted header types for each header e.g.::

                {
                    (header_index, header_name): ["char", "text", ...],
                    ...
                }
        """
        headers_types = {}
        for column_index, header_name in enumerate(headers):
            # Rows may be shorter than the header row (ragged CSV, or a file
            # whose last columns are blank); treat the missing cells as empty
            # rather than raising IndexError, which the caller's blanket handler
            # would turn into a raw "list index out of range" in the UI.
            preview_values = [
                record[column_index] if column_index < len(record) else ''
                for record in preview
            ]
            type_field = self._extract_header_types(preview_values, options)
            headers_types[(column_index, header_name)] = type_field
        return headers_types

    def _get_mapping_suggestion(self, header, fields_tree, header_types, mapping_fields):
        """ Attempts to match a given header to a field of the imported model.

            We can distinguish 2 types of header format:

            - simple header string that aim to directly match a field of the target model
              e.g.: "lead_id" or "Opportunities" or "description".
            - composed '/' joined header string that aim to match a field of a
              relation field of the target model (= subfield) e.g.:
              'lead_id/description' aim to match the field ``description`` of the field lead_id.

            When returning result, to ease further treatments, the result is
            returned as a list, where each element of the list is a field or
            a sub-field of the preceding field.

            - ``["lead_id"]`` for simple case = simple matching
            - ``["lead_id", "description"]`` for composed case = hierarchy matching

            Mapping suggestion is found using the following heuristic:

            - first we check if there was a saved mapping by the user
            - then try to make an exact match on the field technical name /
              english label / translated label
            - finally, try the "fuzzy match": word distance between the header
              title and the field technical name / english label / translated
              label, using the lowest result. The field used for the fuzzy match
              are based on the field types we extracted from the header data
              (see :meth:`_extract_header_types`).

            For subfields, use the same logic.

            Word distance is a score between 0 and 1 to express the distance
            between two char strings where ``0`` denotes an exact match and
            ``1`` indicates completely different strings

            In order to keep only one column matched per field, we return the
            distance. That distance will be used during the deduplicate process
            (see :meth:`_deduplicate_mapping_suggestions`) and only the
            mapping with the smallest distance will be kept in case of multiple
            mapping on the same field. Note that we don't need to return the
            distance in case of hierachy mapping as we consider that as an
            advanced behaviour. The deduplicate process will ignore hierarchy
            mapping. The user will have to manually select on which field he
            wants to map what in case of mapping duplicates for sub-fields.

            :param str header: header name from the file
            :param list fields_tree: list of all the field of the target model
                Coming from :meth:`get_fields_tree`
                e.g: ``[ { 'name': 'fieldName', 'string': 'fieldLabel', fields: [ { 'name': 'subfieldName', ...} ]} , ... ]``
            :param list header_types: Extracted field types for each column in the parsed file, based on its data content.
                Coming from :meth:`_extract_header_types`
                e.g.: ``['int', 'float', 'char', 'many2one', ...]``
            :param dict mapping_fields: contains the previously saved mapping between header and field for the current model.
                E.g.: ``{ header_name: field_name }``
            :returns: if the header couldn't be matched: an empty dict
                      else: a dict with the field path and the distance between header and the matched field.
            :rtype: ``dict(field_path + Word distance)``

                    In case of simple matching: ``{'field_path': [field_name], distance: word_distance}``
                                           e.g.: ``{'field_path': ['lead_id'], distance: 0.23254}``
                    In case of hierarchy matching: ``{'field_path': [parent_field_name, child_field_name, subchild_field_name]}``
                                              e.g.: ``{'field_path': ['lead_id', 'description']}``
        """
        if not fields_tree:
            return {}

        # First, check in saved mapped fields
        mapping_field_name = mapping_fields.get(_normalize_column_name(header))
        # A saved mapping outlives the field it points at: renaming or removing
        # the field (or uninstalling the module that defined it) leaves a row in
        # `base_import.mapping` that was replayed verbatim, with distance -1 --
        # the highest possible priority -- so the column was claimed by a path
        # the client cannot resolve and ended up silently unmapped, suppressing
        # the suggestion it would otherwise have received.
        if mapping_field_name and self._mapping_path_exists(mapping_field_name, fields_tree):
            return {
                'field_path': mapping_field_name.split('/'),
                'distance': -1  # Trick to force to keep that match during mapping deduplication.
            }

        # `get_field_string` rebuilds a {field: label} dict on every call; it was
        # invoked once per candidate field per header (475 calls for 5 headers on
        # res.partner, all for the same handful of models). Memoize per call tree.
        field_strings_en = self._get_field_strings_en()

        if '/' not in header:
            for field in fields_tree:
                fname = field['name']
                # exact match found based on the field technical name
                if header.casefold() == fname.casefold():
                    break
                # match found using either user translation, either model defined field label
                if header.casefold() == field['string'].casefold():
                    break
                strings_en = field_strings_en(field['model_name'])
                if fname in strings_en and header.casefold() == strings_en[fname].casefold():
                    break
            else:
                field = None

            if field:  # found an exact match, no need to go further
                return {
                    'field_path': [field['name']],
                    'distance': 0
                }

            # If no match found, try fuzzy match on fields filtered based on extracted header types
            # Filter out fields with types that does not match corresponding header types.
            filtered_fields = self._filter_fields_by_types(fields_tree, header_types)
            if not filtered_fields:
                return {}

            min_dist = 1
            min_dist_field = False
            for field in filtered_fields:
                fname = field['name']
                # use string distance for fuzzy match only on most likely field types
                distances = [
                    self._get_distance(header.casefold(), fname.casefold()),
                    self._get_distance(header.casefold(), field['string'].casefold()),
                ]

                if field_string_en := field_strings_en(field['model_name']).get(fname):
                    distances.append(
                        self._get_distance(header.casefold(), field_string_en.casefold()),
                    )

                # Keep only the closest mapping suggestion. Note that in case of multiple mapping on the same field,
                # a mapping suggestion could be canceled by another one that has a smaller distance on the same field.
                # See 'deduplicate_mapping_suggestions' method for more info.
                current_field_dist = min(distances)
                if current_field_dist < min_dist:
                    min_dist_field = fname
                    min_dist = current_field_dist

            if min_dist < self.FUZZY_MATCH_DISTANCE:
                return {
                    'field_path': [min_dist_field],
                    'distance': min_dist
                }

            return {}

        # relational field path
        field_path = []
        subfields_tree = fields_tree
        # Iteratively dive into fields tree
        for sub_header in header.split('/'):
            # Strip sub_header in case spaces are added around '/' for
            # readability of paths
            # Skip Saved mapping (mapping_field = {})
            match = self._get_mapping_suggestion(sub_header.strip(), subfields_tree, header_types, {})
            # Any match failure, exit
            if not match:
                return {}
            # prep subfields for next iteration within match['field_path'][0]
            field_name = match['field_path'][0]
            subfields_tree = next(item['fields'] for item in subfields_tree if item['name'] == field_name)
            field_path.append(field_name)
        # No need to return distance for hierarchy mapping
        return {'field_path': field_path}

    def _get_field_strings_en(self):
        """ Return a memoized ``model_name -> {field: english label}`` lookup,
        cached for the lifetime of the returned callable.
        """
        IrModelFieldsUs = self.with_context(lang='en_US').env['ir.model.fields']

        @functools.cache
        def lookup(model_name):
            return IrModelFieldsUs.get_field_string(model_name)

        return lookup

    def _mapping_path_exists(self, field_path, fields_tree):
        """ Whether ``field_path`` (a ``'/'``-joined saved mapping) still
        resolves against ``fields_tree``.

        :param str field_path: e.g. ``'partner_id/name'``
        :param list fields_tree: as built by :meth:`get_fields_tree`
        :rtype: bool
        """
        subtree = fields_tree
        for name in field_path.split('/'):
            match = next((f for f in subtree if f['name'] == name), None)
            if match is None:
                return False
            subtree = match.get('fields') or []
        return True

    def _get_distance(self, a, b):
        """ Return a score between 0 and 1 for the distance between strings
        ``a`` and ``b`` (``0`` = exact match, ``1`` = completely different).
        """
        return 1 - difflib.SequenceMatcher(None, a, b).ratio()

    def _get_mapping_suggestions(self, headers, header_types, fields_tree):
        """ Attempts to match the imported model's fields to the
            titles of the parsed CSV file, if the file is supposed to have
            headers.

            Returns a dict mapping cell indices to key paths in the ``fields`` tree.

            :param list headers: titles of the parsed file
            :param dict header_types:

                extracted types for each column in the parsed file e.g.::

                    {
                        (header_index, header_name): ['int', 'float', 'char', 'many2one',...],
                         ...
                    }

            :param list fields_tree:

                list of the target model's fields e.g.::

                    [
                        {
                            'name': 'fieldName',
                            'string': 'fieldLabel',
                            'fields': [{ 'name': 'subfieldName', ...}]
                        },
                        ...
                    ]

            :rtype: dict[(int, str), {'field_path': list[str], 'distance': int}]
            :returns: mapping_suggestions e.g.:

                .. code-block:: python

                    {
                        (header_index, header_name): {
                            'field_path': ['child_id','name'],
                            'distance': 0
                        },
                        ...
                    }
        """
        mapping_suggestions = {}
        mapping_records = self.env['base_import.mapping'].search_read([('res_model', '=', self.res_model)], ['column_name', 'field_name'])
        # Normalised on read too: rows written before `_normalize_column_name`
        # existed can carry untrimmed names.
        mapping_fields = {_normalize_column_name(rec['column_name']): rec['field_name'] for rec in mapping_records}
        for index, header in enumerate(headers):
            match_field = self._get_mapping_suggestion(header, fields_tree, header_types[(index, header)], mapping_fields)
            mapping_suggestions[(index, header)] = match_field or None

        self._deduplicate_mapping_suggestions(mapping_suggestions)
        return mapping_suggestions

    def _deduplicate_mapping_suggestions(self, mapping_suggestions):
        """ This method is meant to avoid multiple columns to be matched on the same field.

        Taking ``mapping_suggestions`` as input, it will check if multiple
        columns are mapped to the same field and will only keep the mapping
        that has the smallest distance. The other columns that were matched
        to the same field are removed from the mapping suggestions.

        Hierarchy mapping is considered as advanced and is skipped during this
        deduplication process. We consider that multiple mapping on hierarchy
        mapping will not occur often and due to the fact that this won't lead
        to any particular issues when a non 'char/text' field is selected more
        than once in the UI, we keep only the last selected mapping. The
        objective is to lighten the mapping suggestion process as much as we can.

        :param dict mapping_suggestions: ``{ (column_index, header_name) : { 'field_path': [header_name], 'distance': word_distance }}``
        """
        min_dist_per_field = {}
        headers_to_keep = []
        for header, suggestion in mapping_suggestions.items():
            if suggestion is None or len(suggestion['field_path']) > 1:
                headers_to_keep.append(header)
                continue

            field_name = suggestion['field_path'][0]
            field_distance = suggestion['distance']

            best_distance, _best_header = min_dist_per_field.get(field_name, (1, None))
            if field_distance < best_distance:
                min_dist_per_field[field_name] = (field_distance, header)

        headers_to_keep += [value[1] for value in min_dist_per_field.values()]
        for header in mapping_suggestions.keys() - headers_to_keep:
            del mapping_suggestions[header]

    def parse_preview(self, options, count=10):
        """ Generates a preview of the uploaded files, and performs
            fields-matching between the import's file data and the model's
            columns.

            If the headers are not requested (not options.has_headers),
            returned ``matches`` and ``headers`` are both ``False``.

            :param int count: number of preview lines to generate
            :param options: format-specific options.
                            CSV: {quoting, separator, headers}
            :type options: {str, str, str, bool}
            :returns: ``{fields, matches, headers, preview} | {error, preview}``
            :rtype: {dict(str: dict(...)), dict(int, list(str)), list(str), list(list(str))} | {str, str}
        """
        self.ensure_one()
        fields_tree = self.get_fields_tree(self.res_model)
        try:
            data_rows = self._read_file(options)
            if not data_rows:
                raise ImportValidationError(_("Import file has no content or is corrupt"))

            preview = data_rows[:count]

            # Get file headers
            if options.get('has_headers') and preview:
                # We need the header types before matching columns to fields
                headers = preview.pop(0)
                header_types = self._extract_headers_types(headers, preview, options)
            else:
                header_types, headers = {}, []

            # Get matches: the ones already selected by the user or propose a new matching.
            matches = {}
            # If user checked to the advanced mode, we re-parse the file but we keep the mapping "as is".
            # No need to make another mapping proposal
            if options.get('keep_matches') and options.get('fields'):
                for index, match in enumerate(options.get('fields', [])):
                    if match:
                        matches[index] = match.split('/')
            elif options.get('has_headers'):
                matches = self._get_mapping_suggestions(headers, header_types, fields_tree)
                # remove header_name for matches keys as tuples are no supported in json.
                # and remove distance from suggestion (keep only the field path) as not used at client side.
                matches = {
                    header_key[0]: suggestion['field_path']
                    for header_key, suggestion in matches.items()
                    if suggestion
                }

            # compute if we should activate advanced mode or not:
            # if was already activated of if file contains "relational fields".
            if options.get('keep_matches'):
                advanced_mode = options.get('advanced')
            else:
                # Check is label contain relational field
                has_relational_header = any(len(models.fix_import_export_id_paths(col)) > 1 for col in headers)
                # Check is matches fields have relational field
                has_relational_match = any(len(match) > 1 for match in matches.values() if match)
                advanced_mode = has_relational_header or has_relational_match

            column_example = self._build_column_examples(headers, preview, options)

            # Data rows only, i.e. excluding the header that was popped above.
            num_rows = len(data_rows) - (1 if headers else 0)
            # Whether the file needs more than one `execute_import` round trip.
            # This used to be derived with `itertools.islice(data_rows,
            # limit - count, ...)`, an offset that is only correct if the
            # preview has already *consumed* the first `count` rows from a lazy
            # generator. `_read_file` returns a list, so the probe landed
            # `count` rows (plus the header) short and the flag over-reported
            # batching for any limit within `count` of the row count.
            batch_cutoff = options.get('limit')
            batch = bool(batch_cutoff) and num_rows > batch_cutoff

            return {
                'fields': fields_tree,
                'matches': matches or False,
                'headers': headers or False,
                'header_types': list(header_types.values()) or False,
                'preview': column_example,
                'options': options,
                'advanced_mode': advanced_mode,
                'debug': self.env.user.has_group('base.group_no_one'),
                'batch': batch,
                # Data rows only. This drives the client's batch count
                # (`totalSteps = ceil((num_rows - skip) / limit)`); counting the
                # header row in it made that count one too high.
                'num_rows': num_rows,
            }
        except Exception as error:
            # Due to lazy generators, UnicodeDecodeError (for
            # instance) may only be raised when serializing the
            # preview to a list in the return.
            #
            # Expected failures carry a message written for the user and are
            # reported verbatim. Anything else is a defect in this code: it used
            # to be reported the same way, so the user saw raw Python text
            # ("list index out of range" was a real one, from a header-only
            # file) while the only trace was a debug-level log line that no
            # deployment has enabled -- the bug was invisible to monitoring and
            # unactionable to the user. Log those loudly and say something
            # honest instead.
            if isinstance(error, ImportValidationError | UserError | ValueError | csv.Error):
                message = str(error)
            else:
                _logger.exception("Unexpected error while parsing the import preview")
                message = _("The file could not be read. Please check the format options, or contact your administrator if the problem persists.")
            preview = None
            if self.file_type == 'text/csv' and self.file:
                preview = self.file[:ERROR_PREVIEW_BYTES].decode('iso-8859-1')
            return {
                'error': message,
                # iso-8859-1 ensures decoding will always succeed,
                # even if it yields non-printable characters. This is
                # in case of UnicodeDecodeError (or csv.Error
                # compounded with UnicodeDecodeError)
                'preview': preview,
            }

    def _build_column_examples(self, headers, preview, options):
        """ Up to 5 example values per column, for the mapping UI.

        The client shows the first one inline and the rest on hover.

        :param list headers: header labels, empty when the file has none
        :param list preview: the first data rows
        :param dict options: parsing options (supplies the date formats)
        :returns: one list of example strings per column, never empty
        :rtype: list[list[str]]
        """
        # Column count comes from the header when there is no data row left
        # (a header-only file). `preview[0]` was indexed unconditionally, so
        # such a file raised IndexError, which parse_preview's blanket handler
        # turned into the literal string "list index out of range" shown to
        # the user. Now the columns are listed with empty examples and the
        # file stays mappable.
        column_count = max(len(headers), *(len(row) for row in preview or [[]]))
        datetime_format = options.get('datetime_format') or DEFAULT_SERVER_DATETIME_FORMAT
        date_format = options.get('date_format') or DEFAULT_SERVER_DATE_FORMAT

        column_examples = []
        for column_index in range(column_count):
            values = []
            for record in preview:
                # Rows may be shorter than the header (ragged CSV); treat the
                # missing cells as empty rather than raising IndexError.
                value = record[column_index] if column_index < len(record) else ''
                if value and isinstance(value, str):
                    values.append("%s%s" % (value[:50], "..." if len(value) > 50 else ""))
                elif isinstance(value, datetime.datetime):
                    values.append(value.strftime(datetime_format))
                elif isinstance(value, datetime.date):
                    values.append(value.strftime(date_format))
                if len(values) == 5:
                    break
            # blank value if no example was found at all for this column
            column_examples.append(values or [""])
        return column_examples

    @api.model
    def _convert_import_data(
        self,
        fields: Sequence[str | bool],
        options,
    ) -> tuple[
        list[list[str]],  # data
        list[str],        # fields, without the bool items
    ]:
        """ Extracts the input BaseModel and fields list (with
            ``False``-y placeholders for fields to *not* import) into a
            format Model.import_data can use: a fields list without holes
            and the precisely matching data matrix

            :returns: (data, fields)
            :raises ValueError: in case the import data could not be converted
        """
        # Get indices for non-empty fields
        indices = [index for index, field in enumerate(fields) if field]
        if not indices:
            raise ImportValidationError(_("You must configure at least one field to import"))
        # If only one index, itemgetter will return an atom rather
        # than a 1-tuple
        if len(indices) == 1:
            def mapper(row):
                return [row[indices[0]]]
        else:
            mapper = operator.itemgetter(*indices)
        # Get only list of actually imported fields
        import_fields = [f for f in fields if f]

        rows_to_import = self._read_file(options)
        if not rows_to_import:
            # Reachable when called directly (RPC/automation) without going through
            # parse_preview's file_length guard first: an empty or all-blank-rows
            # file used to crash here with an unhandled IndexError (t24068 F4).
            raise ImportValidationError(_("Import file has no content or is corrupt"))
        if len(rows_to_import[0]) != len(fields):
            raise ImportValidationError(
                _(
                    "Error while importing records: all rows should be of the same size, but the title row has %(title_row_entries)d entries while the first row has %(first_row_entries)d. You may need to change the separator character.",
                    title_row_entries=len(fields),
                    first_row_entries=len(rows_to_import[0]),
                ),
            )

        if options.get('has_headers'):
            rows_to_import = rows_to_import[1:]

        # The width check above only ever looked at the *first* row, so a row
        # narrower than the header later in the file reached `mapper` --
        # `operator.itemgetter` over a short row -- and raised IndexError.
        # `execute_import` catches only ImportValidationError, so that escaped
        # as an HTTP 500, while the precise, translated message for exactly
        # this situation sat unused a few lines above. Report it per row, and
        # name the row so the user can find it.
        max_index = indices[-1]
        data = []
        for row_number, row in enumerate(rows_to_import, start=2 if options.get('has_headers') else 1):
            if len(row) <= max_index:
                raise ImportValidationError(_(
                    "Error while importing records: all rows should be of the same size, "
                    "but the title row has %(title_row_entries)d entries while row "
                    "%(row_number)d has %(row_entries)d. You may need to change the "
                    "separator character.",
                    title_row_entries=len(fields),
                    row_number=row_number,
                    row_entries=len(row),
                ))
            mapped = list(mapper(row))
            # don't try inserting completely empty rows (e.g. from
            # filtering out o2m fields)
            if any(mapped):
                data.append(mapped)

        # slicing needs to happen after filtering out empty rows as the
        # data offsets from load are post-filtering
        return data[options.get('skip') or 0:], import_fields

    def _batch_window(self, import_fields, data, limit):
        """ Number of leading rows of ``data`` that this batch can possibly
        consume, so the caller can drop the rest before any per-row work.

        Everything between :meth:`_convert_import_data` and ``load`` used to run
        over *all* remaining rows, because only ``load`` honours the batch
        limit. That made each stage quadratic in the file size (measured: 1.8x
        redundant row visits at 5k rows, 5.5x at 20k), and for binary columns it
        was not merely wasteful -- ``_parse_import_data`` downloads remote image
        URLs, so a 50-URL file imported at limit 5 performed 50 fetches in the
        first batch and 275 overall instead of 50.

        The bound mirrors ``_extract_records``: it stops at row index ``limit``,
        but a record started before that point absorbs the immediately following
        *one2many continuation* rows (rows carrying only o2m values). Those
        trailing rows must stay in the window or the record loses part of its
        one2many lines and they are re-read as a broken record next batch.

        :param list import_fields: field paths, positionally matching ``data``
        :param list data: rows remaining after ``skip``
        :param limit: batch size, or a falsy value for "no batching"
        :rtype: int
        """
        if not limit or limit >= len(data):
            return len(data)

        model = self.env[self.res_model]
        o2m_indexes, other_indexes = [], []
        for index, path in enumerate(import_fields):
            field = model._fields.get(path.split('/')[0])
            (o2m_indexes if field is not None and field.type == 'one2many' else other_indexes).append(index)

        if not o2m_indexes:
            return limit

        window = limit
        while window < len(data):
            row = data[window]
            only_o2m = (
                any(row[i] for i in o2m_indexes if i < len(row))
                and not any(row[i] for i in other_indexes if i < len(row))
            )
            if not only_o2m:
                break
            window += 1
        return window

    @api.model
    def _remove_currency_symbol(self, value, currency_symbols=None):
        """ Strip a leading/trailing currency symbol off ``value``.

        :param str value: the raw cell value
        :param set currency_symbols: known symbols, from :meth:`_currency_symbols`.
            Callers in a loop should pass it; ``None`` falls back to a lookup
            for this one symbol, preserving the behaviour of external callers.
        :returns: the numeric part, or ``False`` if this is not a decorated number
        """
        value = value.strip()
        negative = False
        # Careful that some countries use () for negative so replace it by - sign
        if value.startswith('(') and value.endswith(')'):
            value = value[1:-1]
            negative = True
        split_value = [g for g in _FLOAT_RE.split(value) if g]
        if len(split_value) > 2:
            # This is probably not a float
            return False
        if len(split_value) == 1:
            if _FLOAT_RE.search(split_value[0]) is not None:
                return split_value[0] if not negative else '-' + split_value[0]
            return False
        else:
            # String has been split in 2, locate which index contains the float and which does not
            currency_index = 0
            if _FLOAT_RE.search(split_value[0]) is not None:
                currency_index = 1
            # Check that currency exists
            symbol = split_value[currency_index].strip()
            if currency_symbols is None:
                known = bool(self.env['res.currency'].search_count([('symbol', '=', symbol)], limit=1))
            else:
                known = symbol in currency_symbols
            if known:
                return split_value[(currency_index + 1) % 2] if not negative else '-' + split_value[(currency_index + 1) % 2]
            # Otherwise it is not a float with a currency symbol
            return False

    @api.model
    def _currency_symbols(self):
        """ Every known currency symbol, as one query.

        :meth:`_remove_currency_symbol` is called once per value, so letting it
        look symbols up individually meant a currency-decorated column ("$ 1.50",
        ...) issued one ``res.currency`` SELECT *per row* (300 rows -> 300
        queries). Callers that loop hoist this out of the loop and pass the
        result down. Deliberately not ormcached: a registry-level cache would go
        stale when a currency is added, and one query per import stage is
        already negligible.
        """
        symbols = self.env['res.currency'].with_context(active_test=False).search([]).mapped('symbol')
        return {s for s in symbols if s}

    @api.model
    def _parse_float_from_data(self, data, index, name, options):
        currency_symbols = self._currency_symbols()
        for line in data:
            # The xls/xlsx readers hand back native date/datetime objects for
            # date-formatted cells. Landing one in a float column used to raise
            # a bare AttributeError ('datetime.date' object has no attribute
            # 'strip') which escaped execute_import -- it only catches
            # ImportValidationError -- and surfaced as an HTTP 500. Re-stringify
            # first so it fails as a normal, per-column import error instead.
            line[index] = self._stringify_date_like_objects(line[index], options, trim=True)
            if not line[index]:
                continue
            thousand_separator, decimal_separator = self._infer_separators(line[index], options)

            if 'E' in line[index] or 'e' in line[index]:
                tmp_value = line[index].replace(thousand_separator, '.')
                try:
                    tmp_value = f'{float(tmp_value):f}'
                    line[index] = tmp_value
                    thousand_separator = ' '
                except ValueError:
                    pass

            line[index] = line[index].replace(thousand_separator, '').replace(decimal_separator, '.')
            old_value = line[index]
            line[index] = self._remove_currency_symbol(line[index], currency_symbols)
            if line[index] is False:
                raise ImportValidationError(_("Column %(column)s contains incorrect values (value: %(value)s)", column=name, value=old_value), field=name)

    def _infer_separators(self, value, options):
        """ Try to infer the shape of the separators: if there are two
        different "non-numberic" characters in the number, the
        former/duplicated one would be grouping ("thousands" separator) and
        the latter would be the decimal separator. The decimal separator
        should furthermore be unique.
        """
        # can't use \p{Sc} using re so handroll it
        non_number = [
            # any character
            c for c in value
            # which is not a numeric decoration (() is used for negative
            # by accountants)
            if c not in '()-+'
            # which is not a digit or a currency symbol
            if unicodedata.category(c) not in ('Nd', 'Sc')
        ]

        counts = collections.Counter(non_number)
        # if we have two non-numbers *and* the last one has a count of 1,
        # we probably have grouping & decimal separators
        if len(counts) == 2 and counts[non_number[-1]] == 1:
            return [character for character, _count in counts.most_common()]

        # otherwise get whatever's in the options, or fallback to a default
        thousand_separator = options.get('float_thousand_separator', ' ')
        decimal_separator = options.get('float_decimal_separator', '.')
        return thousand_separator, decimal_separator

    def _parse_import_data(self, data, import_fields, options):
        """ Normalise the raw cell values of the date, float and binary columns
        in place, so ``load`` receives values it can accept.

        Walks the *mapped paths* rather than every field of every model
        involved. The previous shape iterated `fields_get()` -- all fields, all
        attributes, per relational level, per batch -- and tested each one
        against ``import_fields`` with a substring scan, so it did O(fields x
        import_fields) work to act on the handful of columns actually mapped.
        It also decided a field was relational purely from the path shape and
        then read ``field['relation']``, a key ``fields_get`` returns only for
        real relations: a client-supplied path like ``name/foo`` (``name`` is a
        Char) raised ``KeyError('relation')``, which `execute_import` does not
        catch, so it surfaced as an HTTP 500 rather than an import error.
        """
        self._validate_import_paths(import_fields)
        for index, path in enumerate(import_fields):
            field = self._resolve_import_path(path)
            if field is None:
                # Unknown leaf or a pseudo-field such as `.id`. Not this
                # method's error to report: `load` validates those and produces
                # a proper per-column message ("Field 'x' does not exist on
                # model 'y'"), so leave the values untouched and let it speak.
                continue
            if field.type in ('date', 'datetime'):
                self._parse_date_from_data(data, index, path, field.type, options)
            elif field.type in ('float', 'monetary'):
                # Parse float, sometimes float values from file have currency symbol or () to denote a negative value
                # We should be able to manage both case
                self._parse_float_from_data(data, index, path, options)
            elif field.type == 'binary' and field.attachment:
                self._parse_binary_from_data(data, index, path, options)
        return data

    def _resolve_import_path(self, path):
        """ The field an import path addresses, or ``None`` if it does not
        address one.

        ``None`` means "not this method's problem": an unknown leaf name, or a
        pseudo-field such as ``.id`` that is not in ``_fields`` at all. ``load``
        validates and reports those itself, with a better message than anything
        available here.

        A path descending *through* a non-relation is a different matter and
        raises -- see :meth:`_validate_import_paths`.

        :param str path: e.g. ``'name'``, ``'partner_id/country_id/code'``
        :rtype: odoo.fields.Field | None
        """
        model = self._resolve_path_model(path)
        if model is None:
            return None
        # A Properties sub-column is written `<field>.<property>`; it is the
        # `properties` field itself that carries the type.
        return self.env[model]._fields.get(path.split('/')[-1].split('.')[0])

    def _resolve_path_model(self, path):
        """ The model the *last* segment of ``path`` belongs to, or ``None`` if
        the path descends through something that is not a relation.
        """
        model = self.res_model
        for segment in path.split('/')[:-1]:
            if model not in self.env:
                return None
            parent = self.env[model]._fields.get(segment)
            if parent is None or not parent.comodel_name:
                return None
            model = parent.comodel_name
        return model if model in self.env else None

    def _validate_import_paths(self, import_fields):
        """ Reject column mappings that descend through a non-relational field.

        ``name/foo`` asks for a subfield of a Char. Both previous behaviours
        were wrong: this module used to raise ``KeyError('relation')`` while
        building its parse plan, escaping ``execute_import`` as an HTTP 500;
        and ``load``, reached with the crash removed, accepts the column,
        silently discards the value and creates the record anyway -- verified,
        ``{'ids': [...], 'messages': []}`` for a row whose only mapped value
        was dropped. Silently importing nothing is worse than crashing.

        Only *intermediate* segments are checked. An unknown leaf, or a
        pseudo-field like ``.id``, is left to ``load`` -- it reports those
        precisely ("Field 'nope' does not exist on model 'res.partner'") and
        pre-empting it here would only produce a worse message.

        :param list[str] import_fields: field paths, as sent by the client
        :raises ImportValidationError: on the first unusable path
        """
        for path in import_fields:
            segments = path.split('/')
            if len(segments) == 1:
                continue
            if self._resolve_path_model(path) is None:
                raise ImportValidationError(
                    _(
                        "Column %(column)s cannot be imported: %(path)s is not a "
                        "relation on model %(model)s, so it has no sub-fields.",
                        column=path, path='/'.join(segments[:-1]), model=self.res_model,
                    ),
                    field=path,
                )

    def _parse_binary_from_data(self, data, index, name, options):
        """ Resolve the binary column at ``index`` to base64 payloads.

        Values may be a URL (fetched), a filename (left for the client's
        attachment pass) or already-base64 data (validated).
        """
        with requests.Session() as session:
            session.stream = True

            for num, line in enumerate(data):
                # A binary/attachment column can receive a native date/datetime
                # object from the xlsx/xls readers instead of a string (e.g. the
                # spreadsheet cell was date-formatted); every branch below
                # (re.match / '.' in ... / b64decode) assumes a string and used to
                # crash with an unhandled TypeError (t24068 F11) — re-stringify
                # first, mirroring the existing _stringify_date_like_objects
                # helper built for exactly this class of value.
                if isinstance(line[index], (datetime.date, datetime.datetime)):
                    line[index] = self._stringify_date_like_objects(line[index], options)
                if re.match(config.get("import_url_regex"), line[index]):
                    if not self.env.user._can_import_remote_urls():
                        raise ImportValidationError(
                            _("You can not import file via URL, check with your administrator or support for the reason."),
                            field=name, field_type='binary'
                        )
                    line[index] = self._import_file_by_url(line[index], session, name, num)
                elif '.' in line[index]:
                    # Detect if it's a filename
                    pass
                else:
                    try:
                        base64.b64decode(line[index], validate=True)
                    except ValueError as e:
                        raise ImportValidationError(
                            _("Found invalid image data, images should be imported as either URLs or base64-encoded data."),
                            field=name, field_type='binary'
                        ) from e

    def _parse_date_from_data(self, data, index, name, field_type, options):
        dt = datetime.datetime
        fmt = fields.Date.to_string if field_type == 'date' else fields.Datetime.to_string
        d_fmt = options.get('date_format') or DEFAULT_SERVER_DATE_FORMAT
        dt_fmt = options.get('datetime_format') or DEFAULT_SERVER_DATETIME_FORMAT
        for num, line in enumerate(data):
            if not line[index] or isinstance(line[index], datetime.date):
                continue

            v = line[index].strip()
            try:
                # first try parsing as a datetime if it's one
                if dt_fmt and field_type == 'datetime':
                    try:
                        line[index] = fmt(dt.strptime(v, dt_fmt))
                        continue
                    except ValueError:
                        pass
                # otherwise try parsing as a date whether it's a date
                # or datetime
                line[index] = fmt(dt.strptime(v, d_fmt))
            except ValueError as e:
                raise ImportValidationError(
                    _("Column %(column)s contains incorrect values. Error in line %(line)d: %(error)s", column=name, line=num + 1, error=e),
                    field=name, field_type=field_type
                ) from e
            except Exception as e:
                raise ImportValidationError(
                    _("Error Parsing Date [%(field)s:L%(line)d]: %(error)s", field=name, line=num + 1, error=e),
                    field=name, field_type=field_type
                ) from e

    def _import_file_by_url(self, url, session, field, line_number):
        """ Imports a file by URL

        :param str url: the original field value
        :param requests.Session session:
        :param str field: name of the field (for logging/debugging)
        :param int line_number: 0-indexed line number within the imported file (for logging/debugging)
        :return: the replacement value
        :rtype: bytes
        """
        assert re.match(config.get("import_url_regex"), url)
        maxsize = config.get("import_file_maxbytes")
        _logger.debug("Trying to import file from URL: %s into field %s, at line %s", url, field, line_number)
        try:
            response = session.get(url, timeout=config.get("import_file_timeout"))
            response.raise_for_status()

            if response.headers.get('Content-Length') and int(response.headers['Content-Length']) > maxsize:
                raise ImportValidationError(
                    _("File size exceeds configured maximum (%s bytes)", maxsize),
                    field=field
                )

            content = bytearray()
            for chunk in response.iter_content(DEFAULT_CHUNK_SIZE):
                content += chunk
                if len(content) > maxsize:
                    raise ImportValidationError(
                        _("File size exceeds configured maximum (%s bytes)", maxsize),
                        field=field
                    )

            if not guess_mimetype(content).startswith('image/'):
                return base64.b64encode(content)

            image = Image.open(io.BytesIO(content))
            w, h = image.size
            if w * h > 42e6:  # Nokia Lumia 1020 photo resolution
                raise ImportValidationError(
                    _("Image size excessive, imported images must be smaller than 42 million pixel"),
                    field=field
                )

            return base64.b64encode(content)
        except ImportValidationError:
            # Let the specific, already-actionable errors raised above (size caps,
            # image-resolution cap) reach the caller as-is: the generic handler
            # below used to re-wrap them into a "Could not retrieve URL" message,
            # losing both the specific text and the field/field_type routing used
            # by the client to attach the error to the right column (t24068 F2).
            raise
        except Exception as e:
            _logger.warning(e, exc_info=True)
            raise ImportValidationError(_("Could not retrieve URL: %(url)s [%(field_name)s: L%(line_number)d]: %(error)s") % {
                'url': url,
                'field_name': field,
                'line_number': line_number + 1,
                'error': e
            }, field=field) from e

    @api.model
    def _stringify_date_like_objects(self, data, options, trim=False):
        # As imported string like datas might be automatically interpreted and imported as date/datetime
        # object by the spreedsheet a reconversion might be needed
        if isinstance(data, datetime.datetime):
            res = data.strftime(options.get('datetime_format') or DEFAULT_SERVER_DATETIME_FORMAT)
        elif isinstance(data, datetime.date):
            res = data.strftime(options.get('date_format') or DEFAULT_SERVER_DATE_FORMAT)
        else:
            res = data
        return res.strip() if trim else res

    def execute_import(self, fields, columns, options, dryrun=False):
        """ Actual execution of the import

        :param fields: import mapping: maps each column to a field,
                       ``False`` for the columns to ignore
        :type fields: list(str|bool)
        :param columns: columns label
        :type columns: list(str|bool)
        :param dict options:
        :param bool dryrun: performs all import operations (and
                            validations) but rollbacks writes, allows
                            getting as much errors as possible without
                            the risk of clobbering the database.
        :returns: A list of errors. If the list is empty the import
                  executed fully and correctly. If the list is
                  non-empty it contains dicts with 3 keys:

                  ``type``
                    the type of error (``error|warning``)
                  ``message``
                    the error message associated with the error (a string)
                  ``record``
                    the data which failed to import (or ``false`` if that data
                    isn't available or provided)
        :rtype: dict(ids: list(int), messages: list({type, message, record}))
        """
        self.ensure_one()
        import_savepoint = self.env.cr.savepoint(flush=False)
        # `try/finally`, not just the `except ImportValidationError` below: the
        # savepoint used to be released only on the success path and on that
        # one expected exception, so anything else escaping the conversion
        # stages left the cursor inside a savepoint that was never closed --
        # `cr._savepoint_depth` grew and never came back down. HTTP discards
        # the transaction anyway, but automation and test callers do not, and
        # the leak long outlived the two crashes that used to reach it.
        released = False
        try:
            import_limit = options.get('limit')
            try:
                input_file_data, import_fields = self._convert_import_data(fields, options)
                # Only `load` used to honour the batch limit, so every stage below
                # ran over the whole remainder of the file on every batch. Trim to
                # what this batch can actually consume first -- see _batch_window.
                input_file_data = input_file_data[:self._batch_window(import_fields, input_file_data, import_limit)]
                # Parse date and float field
                input_file_data = self._parse_import_data(input_file_data, import_fields, options)
            except ImportValidationError as error:
                return {'messages': [error.__dict__]}

            _logger.info('importing %d rows...', len(input_file_data))

            binary_filenames = self._extract_binary_filenames(import_fields, input_file_data)

            import_fields, merged_data = self.with_context(import_options=options)._handle_multi_mapping(import_fields, input_file_data)

            if options.get('fallback_values'):
                merged_data = self._handle_fallback_values(import_fields, merged_data, options['fallback_values'])

            name_create_enabled_fields = options.pop('name_create_enabled_fields', {})
            options.pop('limit', None)
            model = self.env[self.res_model].with_context(
                import_file=True,
                name_create_enabled_fields=name_create_enabled_fields,
                import_set_empty_fields=options.get('import_set_empty_fields', []),
                import_skip_records=options.get('import_skip_records', []),
                _import_limit=import_limit)
            import_result = model.load(import_fields, merged_data)
            _logger.info('done')

            # If transaction aborted, RELEASE SAVEPOINT is going to raise
            # an InternalError (ROLLBACK should work, maybe). Ignore that.
            with contextlib.suppress(psycopg.InternalError):
                import_savepoint.close(rollback=dryrun)
            released = True
            if dryrun:
                # cancel all changes done to the registry/ormcache
                # we need to clear the cache in case any created id was added to an ormcache and would be missing afterward
                self.pool.clear_all_caches()
                # don't propagate to other workers since it was rollbacked
                self.pool.reset_changes()

            # Insert/Update mapping columns when import complete successfully
            if import_result['ids'] and options.get('has_headers'):
                self._save_column_mappings(columns, fields)

            if 'name' in import_fields:
                # `merged_data`, not `input_file_data`: `import_fields` was rebound
                # by _handle_multi_mapping above to the *deduplicated* field list, so
                # its index no longer addresses the pre-merge rows. With two columns
                # mapped to the same field ahead of `name` -- e.g. [city, city, name]
                # -- index('name') is 1, which in the original row is the second
                # `city` cell: the import reported "FR" as the record name.
                index_of_name = import_fields.index('name')
                skipped = options.get('skip', 0)
                # pad front as data doesn't contain anything for skipped lines
                r = import_result['name'] = [''] * skipped
                r.extend(self._stringify_date_like_objects(x[index_of_name], options) for x in merged_data)
            else:
                import_result['name'] = []

            skip = options.get('skip', 0)
            # convert load's internal nextrow to the imported file's
            if import_result['nextrow']: # don't update if nextrow = 0 (= no nextrow)
                import_result['nextrow'] += skip
            if binary_filenames:
                import_result['binary_filenames'] = binary_filenames

            return import_result
        finally:
            if not released:
                with contextlib.suppress(psycopg.InternalError):
                    import_savepoint.close(rollback=True)

    def _save_column_mappings(self, columns, fields):
        """ Remember the column-name -> field mapping so the next import from
        the same source can suggest it.

        :param list columns: column labels, ``False`` for unnamed columns
        :param list fields: field path per column, ``False`` where unmapped
        """
        # Only columns the user actually mapped. Storing the unmapped ones wrote
        # a `field_name = False` row for every ignored column of every import --
        # rows that can never produce a suggestion and are never vacuumed.
        #
        # Normalised through the same helper the *lookup* uses, so the two
        # cannot drift apart again: the client happens to send trimmed and
        # lower-cased labels today, and the round trip silently depended on it.
        wanted = {
            _normalize_column_name(column_name): field_name
            for column_name, field_name in zip(columns, fields, strict=False)
            if column_name and field_name
        }
        if not wanted:
            return

        BaseImportMapping = self.env['base_import.mapping']
        # One search for all columns instead of one per column.
        existing = BaseImportMapping.search([
            ('res_model', '=', self.res_model),
            ('column_name', 'in', list(wanted)),
        ])
        # No dedup pass over `existing`: `_column_unique_per_model` makes
        # (res_model, column_name) unique, so it cannot carry duplicates, and
        # `wanted` is a dict so the incoming side cannot either.
        for mapping in existing:
            field_name = wanted[mapping.column_name]
            if mapping.field_name != field_name:
                mapping.field_name = field_name

        missing = [
            {'res_model': self.res_model, 'column_name': column_name, 'field_name': field_name}
            for column_name, field_name in wanted.items()
            if column_name not in set(existing.mapped('column_name'))
        ]
        if not missing:
            return
        # Savepoint, because this runs *after* a successful `load`: a
        # concurrent import of the same model and column can insert between
        # the search above and this create, and the resulting unique-violation
        # would abort the transaction carrying records that imported fine.
        # Remembering a mapping is a convenience; losing the import is not.
        try:
            with self.env.cr.savepoint():
                BaseImportMapping.create(missing)
        except psycopg.errors.UniqueViolation:
            _logger.debug(
                "concurrent import already stored a mapping for %s; skipping",
                self.res_model,
            )

    def _extract_binary_filenames(self, import_fields, data, model=False, prefix='', binary_filenames=False):
        model = model or self.res_model
        binary_filenames = binary_filenames or defaultdict(list)
        for name, field in self.env[model]._fields.items():
            name = prefix + name
            if any(name + '/' in import_field and name == import_field.split('/')[prefix.count('/')] for import_field in import_fields):
                # Recursive call with the relational as new model and add the field name to the prefix
                binary_filenames = self._extract_binary_filenames(import_fields, data, field.comodel_name, name + '/', binary_filenames)
            elif field.type == 'binary' and field.attachment and name in import_fields:
                index = import_fields.index(name)
                for line in data:
                    filename = None
                    value = line[index]
                    if isinstance(value, str):
                        if re.match(config.get("import_url_regex"), value):
                            pass
                        elif '.' in value:
                            # Detect if it's a filename
                            filename = value
                            line[index] = ''
                        # else base64 nothing to do
                    binary_filenames[name].append(filename)
        return binary_filenames

    def _handle_multi_mapping(self, import_fields, input_file_data):
        """ This method handles multiple mapping on the same field.

        It will return the list of the mapped fields and the concatenated data for each field:

        - If two column are mapped on the same text or char field, they will end up
          in only one column, concatenated via space (char) or new line (text).
        - The same logic is used for many2many fields. Multiple values can be
          imported if they are separated by ``,``.

        Input/output Example:

        input data
            .. code-block:: python

                [
                    ["Value part 1", "1", "res.partner_id1", "Value part 2"],
                    ["I am", "1", "res.partner_id1", "Batman"],
                ]

        import_fields
            ``[desc, some_number, partner, desc]``

        output merged_data
            .. code-block:: python

                [
                    ["Value part 1 Value part 2", "1", "res.partner_id1"],
                    ["I am Batman", "1", "res.partner_id1"],
                ]
        fields
            ``[desc, some_number, partner]``
        """
        # Get fields and their occurrences indexes
        # Among the fields that have been mapped, we get their corresponding mapped column indexes
        # as multiple fields could have been mapped to multiple columns.
        mapped_field_indexes = {}
        for idx, field_path in enumerate(field_path for field_path in import_fields if field_path):
            mapped_field_indexes.setdefault(field_path, []).append(idx)
        import_fields = list(mapped_field_indexes.keys())
        import_options = self.env.context.get('import_options', {})

        # Resolve each mapped field ONCE, ahead of the row loop. This walk
        # (`self.env[model]._fields.get(...)` per path segment) used to sit
        # inside the per-row loop even though nothing in it depends on the row:
        # a 20k-row file mapped to 3 columns performed 60k identical registry
        # resolutions. Measured 221.6 ms -> 30.1 ms.
        #
        # `_resolve_import_path` walks by *position*, which also fixes a
        # self-referential path such as 'parent_id/parent_id': the previous
        # walk compared each segment to the last one by name, so the first
        # segment matched and the model was left un-retargeted.
        merge_plan = []
        for field_path, indexes in mapped_field_indexes.items():
            field = self._resolve_import_path(field_path)
            field_type = field.type if field else ''
            merge_plan.append((
                indexes,
                field_type,
                CONCAT_SEPARATOR_IMPORT.get(field_type),
                # Trim trailing whitespaces before joining
                field_type == 'char' and field.trim,
            ))

        # recreate data and merge duplicates (applies to char, text, html and many2many fields)
        # Also handles multi-mapping on "field of relation fields".
        merged_data = []
        for record in input_file_data:
            new_record = []
            for indexes, field_type, separator, trim in merge_plan:
                # merge data if necessary
                if separator is not None:
                    # `_stringify_date_like_objects` on every branch: the
                    # xls/xlsx readers can put a native date in a char or
                    # many2many column, and str.join on it raised a bare
                    # TypeError that escaped execute_import as an HTTP 500.
                    new_record.append(separator.join(
                        self._stringify_date_like_objects(record[idx], import_options, trim)
                        for idx in indexes if record[idx]
                    ))
                elif field_type == 'properties':
                    # for property fields date and datetime objects are not suitable for JSON values
                    new_record.append(self._stringify_date_like_objects(record[indexes[0]], import_options))
                else:
                    new_record.append(record[indexes[0]])

            merged_data.append(new_record)

        return import_fields, merged_data

    def _handle_fallback_values(self, import_field, input_file_data, fallback_values):
        """
        If there are fallback values, this method will replace the input file
        data value if it does not match the possible values for the given field.
        This is only valid for boolean and selection fields.

        .. note::

            We can consider that we need to retrieve the selection values for
            all the fields in fallback_values, as if they are present, it's because
            there was already a conflict during first import run and user had to
            select a fallback value for the field.

        :param list import_field: ordered list of field that have been matched to import data
        :param list input_file_data: ordered list of values (list) that need to be imported in
            the given import_fields
        :param dict fallback_values:

            contains all the fields that have been tagged by the user to use a
            specific fallback value in case the value to import does not match
            values accepted by the field (selection or boolean) e.g.::

                {
                    'fieldName': {
                        'fallback_value': fallback_value,
                        'field_model': field_model,
                        'field_type': field_type
                    },
                    'state': {
                        'fallback_value': 'draft',
                        'field_model': field_model,
                        'field_type': 'selection'
                    },
                    'active': {
                        'fallback_value': 'true',
                        'field_model': field_model,
                        'field_type': 'boolean'
                    }
                }
        """
        # add possible selection values into our fallback dictionary for fields of type "selection"
        for field_string in fallback_values:
            if fallback_values[field_string]['field_type'] != "selection":
                continue
            field_path = field_string.split('/')
            target_field = field_path[-1]
            target_model = self.env[fallback_values[field_string]['field_model']]

            # A Properties sub-column ("<field>.<property>") is not a field of
            # the model, so fields_get returns nothing for it and indexing the
            # result raised KeyError -- an HTTP 500 rather than an import error.
            # The client already sends the selection for those (it reads it off
            # the field tree), so honour that and only fall back to fields_get.
            description = target_model.fields_get([target_field]).get(target_field) or {}
            selection = description.get('selection')
            if selection is None:
                selection = fallback_values[field_string].get('selection') or []
            selection_values = [str(value).lower() for _key, value in selection]
            fallback_values[field_string]['selection_values'] = selection_values

        # check fallback values
        for record_index, records in enumerate(input_file_data):
            for column_index, value in enumerate(records):
                field = import_field[column_index]

                if field in fallback_values:
                    fallback_value = fallback_values[field]['fallback_value']
                    # A spreadsheet date cell reaching here is not a str, and
                    # `.lower()` on it raised a bare AttributeError that escaped
                    # execute_import as an HTTP 500.
                    value = self._stringify_date_like_objects(value, self.env.context.get('import_options', {}))
                    # Boolean
                    if fallback_values[field]['field_type'] == "boolean":
                        value = value if value.lower() in ('0', '1', 'true', 'false') else fallback_value
                    # Selection
                    elif fallback_values[field]['field_type'] == "selection" and value.lower() not in fallback_values[field]["selection_values"]:
                        value = fallback_value if fallback_value != 'skip' else None  # don't set any value if we skip

                    input_file_data[record_index][column_index] = value

        return input_file_data

